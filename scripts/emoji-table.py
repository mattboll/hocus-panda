#!/usr/bin/env python3
"""Builds crates/hocus-shell/data/emoji.tsv for the emoji picker (#71).

From Unicode's emoji-test.txt and CLDR's annotations (cldr-json, full and
derived) in English and French, all under the Unicode License v3:

    https://unicode.org/Public/emoji/latest/emoji-test.txt
    https://github.com/unicode-org/cldr-json  (cldr-annotations-full,
        cldr-annotations-derived-full; annotations/{en,fr}/annotations.json)

Usage: scripts/emoji-table.py DIR > crates/hocus-shell/data/emoji.tsv, with
the files above in DIR as emoji-test.txt, ann-en.json, der-en.json,
ann-fr.json, der-fr.json.

One line per fully-qualified emoji without a skin tone, in Unicode's order:
emoji, takes a skin tone (1/0), English name, English keywords (|), French
name, French keywords (|).
"""
import json
import sys
from pathlib import Path

TONES = {"\U0001F3FB", "\U0001F3FC", "\U0001F3FD", "\U0001F3FE", "\U0001F3FF"}


def names(directory: Path, lang: str) -> dict:
    out = {}
    for kind, key in (("ann", "annotations"), ("der", "annotationsDerived")):
        data = json.loads((directory / f"{kind}-{lang}.json").read_text())
        for emoji, a in data[key]["annotations"].items():
            out[emoji.replace("️", "")] = a
    return out


def main() -> None:
    directory = Path(sys.argv[1])
    en, fr = names(directory, "en"), names(directory, "fr")
    emojis, toned = [], set()
    for line in (directory / "emoji-test.txt").read_text().splitlines():
        if not line or line.startswith("#") or "; fully-qualified" not in line:
            continue
        codes = line.split(";")[0].split()
        emoji = "".join(chr(int(c, 16)) for c in codes)
        if any(t in emoji for t in TONES):
            toned.add("".join(c for c in emoji if c not in TONES).replace("️", ""))
            continue
        emojis.append(emoji)
    print("# emoji\ttone\ten\ten keywords\tfr\tfr keywords — generated by scripts/emoji-table.py from Unicode CLDR data (Unicode License v3)")
    for emoji in emojis:
        bare = emoji.replace("️", "")
        e, f = en.get(bare), fr.get(bare)
        if not e or not f:
            continue
        clean = lambda words: "|".join(w.replace("\t", " ").replace("|", " ") for w in words)
        print(
            "\t".join(
                [
                    emoji,
                    "1" if bare in toned else "0",
                    clean(e.get("tts", [""]))[:80],
                    clean(e.get("default", [])),
                    clean(f.get("tts", [""]))[:80],
                    clean(f.get("default", [])),
                ]
            )
        )


main()
